"""Class sessions: each one owns a unique token that becomes its check-in link."""
from __future__ import annotations

import secrets
from dataclasses import dataclass
from datetime import date, datetime, time, timedelta
from urllib.parse import urlencode

import pandas as pd

from src.core import events
from src.core.config import now_local, settings
from src.data import database as db
from src.data.student_repository import load_students


@dataclass
class ClassSession:
    id: int
    token: str
    course_name: str
    class_name: str
    lecturer: str
    room: str
    session_date: date
    start_time: time
    end_time: time
    late_after_minutes: int
    departments: list[str]
    enforce_schedule: bool
    is_active: bool
    created_at: str
    course_id: int | None = None  # set for meetings generated by a semester course
    is_cancelled: bool = False

    @classmethod
    def from_row(cls, row: dict) -> "ClassSession":
        course_id = row.get("course_id")
        has_course = course_id is not None and course_id == course_id  # NaN-safe (pandas rows)
        return cls(
            course_id=int(course_id) if has_course else None,
            is_cancelled=bool(row.get("is_cancelled") or 0),
            id=row["id"],
            token=row["token"],
            course_name=row["course_name"],
            class_name=row["class_name"],
            lecturer=row["lecturer"],
            room=row["room"],
            session_date=date.fromisoformat(row["session_date"]),
            start_time=time.fromisoformat(row["start_time"]),
            end_time=time.fromisoformat(row["end_time"]),
            late_after_minutes=int(row["late_after_minutes"]),
            departments=[d for d in row["departments"].split(",") if d],
            enforce_schedule=bool(row["enforce_schedule"]),
            is_active=bool(row["is_active"]),
            created_at=row["created_at"],
        )

    @property
    def title(self) -> str:
        return f"{self.course_name} - {self.class_name}"

    @property
    def starts_at(self) -> datetime:
        return datetime.combine(self.session_date, self.start_time)

    @property
    def ends_at(self) -> datetime:
        return datetime.combine(self.session_date, self.end_time)

    @property
    def opens_at(self) -> datetime:
        """Check-in opens a little before the class starts (students arrive early)."""
        return self.starts_at - timedelta(minutes=settings.checkin_early_minutes)

    @property
    def late_at(self) -> datetime:
        return self.starts_at + timedelta(minutes=self.late_after_minutes)

    @property
    def link(self) -> str:
        return build_link(self.token)

    def state(self, at: datetime | None = None) -> str:
        """One of: cancelled, closed, upcoming, open, ended."""
        at = at or now_local()
        if self.is_cancelled:
            return "cancelled"
        if not self.is_active:
            return "closed"
        if not self.enforce_schedule:
            return "open"
        if at < self.opens_at:
            return "upcoming"
        if at > self.ends_at:
            return "ended"
        return "open"


def expected_by_department(session: ClassSession) -> dict[str, int]:
    """How many registered students each department contributes to this class."""
    students = load_students()
    if session.departments:
        students = students[students["department"].isin(session.departments)]
    return {dept: int(n) for dept, n in students.groupby("department").size().items()}


def session_event(session: ClassSession) -> dict:
    expected = expected_by_department(session)
    return {
        "session_id": session.id,
        "class_title": session.title,
        "course_name": session.course_name,
        "class_name": session.class_name,
        "lecturer": session.lecturer,
        "room": session.room,
        "session_date": session.session_date.isoformat(),
        "start_time": session.start_time.strftime("%H:%M"),
        "end_time": session.end_time.strftime("%H:%M"),
        "departments": session.departments,
        "expected_by_department": expected,
        "expected_total": sum(expected.values()),
    }


def build_link(token: str) -> str:
    return f"{settings.public_base_url.rstrip('/')}/?{urlencode({'class': token})}"


def new_token() -> str:
    """Link token, unique across one-off sessions and semester courses (they share ?class=)."""
    while True:
        token = secrets.token_urlsafe(6).replace("-", "x").replace("_", "y")
        taken = db.fetch_one(
            "SELECT 1 FROM class_sessions WHERE token = ? UNION ALL SELECT 1 FROM courses WHERE token = ?",
            (token, token),
        )
        if not taken:
            return token


def create_session(
    *,
    course_name: str,
    class_name: str,
    lecturer: str,
    room: str,
    session_date: date,
    start_time: time,
    end_time: time,
    late_after_minutes: int = 15,
    departments: list[str] | None = None,
    enforce_schedule: bool = True,
    course_id: int | None = None,
) -> ClassSession:
    if not course_name.strip() or not class_name.strip():
        raise ValueError("Naran kursu no naran klase obrigatóriu.")
    if end_time <= start_time:
        raise ValueError("Oras remata tenke depois oras hahú.")

    token = new_token()
    session_id = db.execute(
        """
        INSERT INTO class_sessions (token, course_name, class_name, lecturer, room, session_date,
            start_time, end_time, late_after_minutes, departments, enforce_schedule, is_active, created_at,
            course_id)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, ?, ?)
        """,
        (
            token,
            course_name.strip(),
            class_name.strip(),
            lecturer.strip(),
            room.strip(),
            session_date.isoformat(),
            start_time.strftime("%H:%M"),
            end_time.strftime("%H:%M"),
            int(late_after_minutes),
            ",".join(departments or []),
            int(enforce_schedule),
            now_local().isoformat(sep=" "),
            course_id,
        ),
    )
    session = get_session(session_id)
    events.publish(events.SESSION_CREATED, session_event(session), event_id=f"ses-{session_id}", key=str(session_id))
    return session


def get_session(session_id: int) -> ClassSession | None:
    row = db.fetch_one("SELECT * FROM class_sessions WHERE id = ?", (session_id,))
    return ClassSession.from_row(row) if row else None


def get_session_by_token(token: str | None) -> ClassSession | None:
    if not token:
        return None
    row = db.fetch_one("SELECT * FROM class_sessions WHERE token = ?", (token.strip(),))
    return ClassSession.from_row(row) if row else None


def list_single_sessions() -> list[ClassSession]:
    """One-off sessions (not generated by a semester course)."""
    rows = db.fetch_df(
        "SELECT * FROM class_sessions WHERE course_id IS NULL ORDER BY session_date DESC, start_time DESC, id DESC"
    )
    return [ClassSession.from_row(r) for r in rows.to_dict("records")]


def cancel_session(session_id: int) -> None:
    """Cancel one meeting (e.g. a public holiday): it no longer counts for attendance or analytics."""
    db.execute("UPDATE class_sessions SET is_cancelled = 1, is_active = 0 WHERE id = ?", (session_id,))
    events.publish(
        events.SESSION_DELETED, {"session_id": session_id}, event_id=f"ses-del-{session_id}", key=str(session_id)
    )


def list_sessions(on_date: date | None = None) -> list[ClassSession]:
    if on_date:
        rows = db.fetch_df(
            "SELECT * FROM class_sessions WHERE session_date = ? ORDER BY start_time, id",
            (on_date.isoformat(),),
        )
    else:
        rows = db.fetch_df("SELECT * FROM class_sessions ORDER BY session_date DESC, start_time DESC, id DESC")
    return [ClassSession.from_row(r) for r in rows.to_dict("records")]


def sessions_frame() -> pd.DataFrame:
    """Sessions with their attendance counts, for admin tables."""
    return db.fetch_df(
        """
        SELECT s.*, COUNT(a.id) AS attendees,
               SUM(CASE WHEN a.status = 'Late' THEN 1 ELSE 0 END) AS late
        FROM class_sessions s
        LEFT JOIN attendance a ON a.session_id = s.id
        GROUP BY s.id
        ORDER BY s.session_date DESC, s.start_time DESC, s.id DESC
        """
    )


def set_active(session_id: int, active: bool) -> None:
    db.execute("UPDATE class_sessions SET is_active = ? WHERE id = ?", (int(active), session_id))


def regenerate_token(session_id: int) -> str:
    """Invalidate a leaked link by issuing a new token."""
    token = new_token()
    db.execute("UPDATE class_sessions SET token = ? WHERE id = ?", (token, session_id))
    return token


def delete_session(session_id: int) -> None:
    db.execute("DELETE FROM class_sessions WHERE id = ?", (session_id,))
    events.publish(
        events.SESSION_DELETED, {"session_id": session_id}, event_id=f"ses-del-{session_id}", key=str(session_id)
    )
